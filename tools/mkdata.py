#!/usr/bin/env python3
"""Write build/cardata.inc (car, part and sound tables) from gamedata.py."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gamedata as gd

TIERS = [0, 0, 1, 1, 2, 2, 2, 3, 3, 4, 4, 5, 5]


def bytes_line(vals):
    return '        .byte ' + ', '.join('$%02X' % (v & 0xFF) for v in vals)


def words(name, vals):
    out = ['%s_l:' % name, bytes_line([v & 0xFF for v in vals]),
           '%s_h:' % name, bytes_line([v >> 8 for v in vals])]
    return out


def main():
    out = []
    o = out.append
    o('; generated by tools/mkdata.py -- do not edit')
    o('NCARS = %d' % gd.NCARS)
    o('NDEALER = %d' % gd.NDEALER)
    o('CRATE_CAR = %d' % gd.CRATE_CAR)
    o('car_names:')
    for c in gd.CARS:
        o('        .byte "%s", 0' % c[0].ljust(12))
    o('car_shape:')
    o(bytes_line([c[1] for c in gd.CARS]))
    out += words('car_hp', [c[2] for c in gd.CARS])
    out += words('car_mass', [c[3] for c in gd.CARS])
    out += words('car_redline', [c[4] for c in gd.CARS])
    o('car_curve:')
    o(bytes_line([c[5] for c in gd.CARS]))
    o('car_ngears:')
    o(bytes_line([c[6] for c in gd.CARS]))
    out += words('car_final', [gd.gear_raw(c[7]) for c in gd.CARS])
    o('car_drive:')
    o(bytes_line([c[8] for c in gd.CARS]))
    o('car_cda:')
    o(bytes_line([int(round(c[9] * 256)) for c in gd.CARS]))
    o('car_price0:')
    o(bytes_line([c[10] & 0xFF for c in gd.CARS]))
    o('car_price1:')
    o(bytes_line([(c[10] >> 8) & 0xFF for c in gd.CARS]))
    o('car_price2:')
    o(bytes_line([c[10] >> 16 for c in gd.CARS]))
    o('car_gems:')
    o(bytes_line([c[11] for c in gd.CARS]))
    o('car_level:')
    o(bytes_line([c[12] for c in gd.CARS]))
    o('car_tier:')
    o(bytes_line(TIERS))
    out += words('car_torque', [gd.car_torque(i) for i in range(gd.NCARS)])
    # default gear sets: 7 words per car
    o('car_gearset:')
    for c in gd.CARS:
        g = [gd.gear_raw(x) for x in gd.car_gears(gd.CARS.index(c))] + [0] * (7 - c[6])
        o('        .word ' + ', '.join('$%04X' % x for x in g))
    o('curve_shapes:')
    for cv in gd.CURVES:
        o(bytes_line(cv))
    o('hp_bonus:')
    o(bytes_line([gd.HP_BONUS.get(p, 0) for p in range(gd.NPARTS)]))
    o('turbo_boost:')
    o(bytes_line(gd.TURBO_BOOST))
    o('turbo_start:')
    o(bytes_line(gd.TURBO_START))
    o('turbo_rate:')
    o(bytes_line(gd.TURBO_RATE))
    o('nos_add_tab:')
    o(bytes_line(gd.NOS_ADD))
    o('nos_frames_tab:')
    o(bytes_line(gd.NOS_FRAMES))
    o('shift_frames_tab:')
    o(bytes_line(gd.SHIFT_FRAMES))
    o('tire_grip:')
    o(bytes_line(gd.TIRE_GRIP))
    out += words('drive_k', gd.DRIVE_K)
    # part prices in $10 units: per part, [tier][level] words (level 0 unused)
    o('part_cost_lo:')
    o('        .byte ' + ', '.join('<part_cost_%d' % p for p in range(gd.NPARTS)))
    o('part_cost_hi:')
    o('        .byte ' + ', '.join('>part_cost_%d' % p for p in range(gd.NPARTS)))
    for p in range(gd.NPARTS):
        o('part_cost_%d:' % p)
        for t in range(6):
            vals = [gd.part_cost(p, t, lv) // 10 for lv in range(5)]
            o('        .word ' + ', '.join(str(v) for v in vals))
    # engine sound: pulse period for rpm>>7 (0..95).  Pitch rises with rpm.
    per = []
    for i in range(96):
        rpm = max(700, i * 128 + 64)
        f = 22 + rpm / 26.0
        p = int(round(1789773 / (16 * f) - 1))
        per.append(min(0x7FF, p))
    out += words('engine_period', per)
    # quarter-square tables for fast multiplication: sq(n) = n*n/4, n 0..511
    sq = [n * n // 4 for n in range(512)]
    o('.align 256')
    for name, vals in (('sqr_lo', [v & 0xFF for v in sq[:256]]), ('sqr_hi', [v >> 8 & 0xFF for v in sq[:256]]),
                       ('sqr2_lo', [v & 0xFF for v in sq[256:]]), ('sqr2_hi', [v >> 8 & 0xFF for v in sq[256:]])):
        o(name + ':')
        for k in range(0, 256, 16):
            o(bytes_line(vals[k:k + 16]))
    open(sys.argv[1], 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
