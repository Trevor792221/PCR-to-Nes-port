#!/usr/bin/env python3
"""World map screen: Japan as NES background tiles.

The coastline (tools/japan_coast.json) is Natural Earth 1:50m country data
(public domain, naturalearthdata.com), cut to the four main islands and the
islets around them.  It is drawn at screen size, every land pixel next to the
sea becomes shore, and the picture is cut into 8x8 tiles:

    build/map.chr      128 BG tiles for $80-$FF (sea is the blank tile $00)
    build/map_nt.bin   960-byte nametable
    build/map_attr.bin 64-byte attribute table (palette 1 where there's land)
    build/map.inc      marker positions for the regions, sea areas for text

    python3 tools/mkmap.py build [preview.png]
"""
import json
import math
import os
import sys

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
SEA, LAND, SHORE = 0, 2, 3

# drawing window: longitude/latitude box -> screen pixels
LON0, LON1, LAT0, LAT1 = 128.6, 145.9, 30.9, 45.6
SIZE = 208                     # the box's larger side, in pixels
OX, OY = 34, 14                # top-left of the box on screen
MIN_AREA = 20                  # drop islets smaller than this (pixels)

# regions in unlock order: name, (lon, lat) of the marker
REGIONS = [
    ('FUKUOKA', (130.40, 33.59)),
    ('HIROSHIMA', (132.46, 34.39)),
    ('OSAKA', (135.50, 34.69)),
    ('NAGOYA', (136.91, 35.18)),
    ('GUNMA', (139.06, 36.39)),
    ('SAPPORO', (141.35, 43.06)),
    ('TOKYO', (139.69, 35.69)),
]

# text areas that must stay on open sea (tile columns/rows, inclusive)
TEXT_AREAS = [(1, 2, 16, 13), (18, 23, 31, 28)]


def project(lon, lat):
    k = math.cos(math.radians(37))
    s = SIZE / max((LON1 - LON0) * k, LAT1 - LAT0)
    return OX + (lon - LON0) * k * s, OY + (LAT1 - lat) * s


def area(pts):
    return abs(sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]))) / 2


def draw():
    im = Image.new('L', (256, 240), SEA)
    d = ImageDraw.Draw(im)
    for ring in json.load(open(os.path.join(HERE, 'japan_coast.json'))):
        pts = [project(x, y) for x, y in ring]
        if area(pts) >= MIN_AREA:
            d.polygon(pts, fill=LAND)
    px = im.load()
    for y in range(240):
        for x in range(256):
            if px[x, y] == LAND and any(not (0 <= x + dx < 256 and 0 <= y + dy < 240)
                                        or px[x + dx, y + dy] == SEA
                                        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                px[x, y] = SHORE
    return im


def tile_bytes(px, tx, ty):
    p0, p1 = [], []
    for y in range(8):
        b0 = b1 = 0
        for x in range(8):
            c = px[tx * 8 + x, ty * 8 + y]
            b0 = b0 << 1 | (c & 1)
            b1 = b1 << 1 | (c >> 1)
        p0.append(b0)
        p1.append(b1)
    return bytes(p0 + p1)


def build():
    im = draw()
    px = im.load()
    blank = bytes(16)
    tiles, nt = [], bytearray()
    land = [[False] * 32 for _ in range(30)]
    for ty in range(30):
        for tx in range(32):
            t = tile_bytes(px, tx, ty)
            if t == blank:
                nt.append(0x00)
                continue
            land[ty][tx] = True
            if t not in tiles:
                tiles.append(t)
            nt.append((0x80 + tiles.index(t)) & 0xFF)
    assert len(tiles) <= 128, 'map needs %d tiles' % len(tiles)
    for x0, y0, x1, y1 in TEXT_AREAS:
        for ty in range(y0, y1 + 1):
            for tx in range(x0, x1 + 1):
                assert not land[ty][tx], 'land under the text at %d,%d' % (tx, ty)
    # attributes: palette 1 for any 16x16 block with land, else 0 (text)
    attr = bytearray(64)
    for by in range(15):
        for bx in range(16):
            if any(land[by * 2 + j][bx * 2 + i] for j in (0, 1) for i in (0, 1)):
                attr[(by // 2) * 8 + bx // 2] |= 1 << ((by % 2) * 4 + (bx % 2) * 2)
    for x0, y0, x1, y1 in TEXT_AREAS:            # the text never shares a block with land
        for ty in range(y0, y1 + 1):
            for tx in range(x0, x1 + 1):
                by, bx = ty // 2, tx // 2
                assert not attr[(by // 2) * 8 + bx // 2] >> ((by % 2) * 4 + (bx % 2) * 2) & 3, \
                    'text block %d,%d has land' % (tx, ty)
    chr_ = b''.join(tiles) + blank * (128 - len(tiles))
    marks = [tuple(int(round(v)) for v in project(*ll)) for _, ll in REGIONS]
    return im, chr_, bytes(nt), bytes(attr), marks, len(tiles)


def main():
    out = sys.argv[1]
    im, chr_, nt, attr, marks, n = build()
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, 'map.chr'), 'wb').write(chr_)
    open(os.path.join(out, 'map_nt.bin'), 'wb').write(nt)
    open(os.path.join(out, 'map_attr.bin'), 'wb').write(attr)
    with open(os.path.join(out, 'map.inc'), 'w') as f:
        f.write('; generated by tools/mkmap.py\n')
        f.write('.assert NREGIONS = %d, error, "tools/mkmap.py has %d regions"\n' % (len(REGIONS), len(REGIONS)))
        f.write('map_mark_x: .byte %s\n' % ', '.join(str(x) for x, y in marks))
        f.write('map_mark_y: .byte %s\n' % ', '.join(str(y) for x, y in marks))
    if len(sys.argv) > 2:
        pv = im.point(lambda v: (10, 0, 150, 255)[v] if v < 4 else 0).convert('RGB')
        d = ImageDraw.Draw(pv)
        for x0, y0, x1, y1 in TEXT_AREAS:
            d.rectangle([x0 * 8, y0 * 8, x1 * 8 + 7, y1 * 8 + 7], outline=(255, 0, 0))
        for x, y in marks:
            d.rectangle([x - 2, y - 2, x + 2, y + 2], fill=(255, 220, 0))
        pv.resize((512, 480), Image.NEAREST).save(sys.argv[2])
    print('map tiles %d/128' % n, file=sys.stderr)


if __name__ == '__main__':
    main()
