# cars.chr / bigcars.chr: the 13 cars in model order (shape = model), then
# highway traffic (cars.chr only), shapes 13-17 in race.s tr_shape order
NCAR_SHAPES = len(CAR_BODIES)
TRAFFIC_ORDER = ['TAXI', 'CVAN', 'LADDER', 'CAMPER', 'REMOVAL']


def car_pixels(name, frame=0):
    """name: a model number (0-12) or a traffic body name"""
    rows, wheels = CAR_BODIES[name] if isinstance(name, int) else BODIES[name]
    assert len(rows) == 16, name
    grid = [list(r) for r in rows]
    for r in rows:
        assert len(r) == 32, (name, r, len(r))
    for cx in wheels:
        for dy, line in enumerate(WHEEL[frame]):
            for dx, ch in enumerate(line):
                if ch != '.':
                    grid[9 + dy][cx - 3 + dx] = ch
    return [''.join(r) for r in grid]
